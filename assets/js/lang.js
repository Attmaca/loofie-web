function setLanguage(lang) {
    const nextLang = translations[lang] ? lang : "tr";
    localStorage.setItem("language", nextLang);
    document.documentElement.lang = nextLang;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");
        const value = translations[nextLang][key];
        if (!value) return;
        if (value.includes("<")) {
            element.innerHTML = value;
        } else {
            element.textContent = value;
        }
    });

    document.querySelectorAll("[data-lang-switch]").forEach((button) => {
        button.textContent = nextLang === "tr" ? "EN" : "TR";
        button.setAttribute("aria-label", nextLang === "tr" ? "Switch to English" : "Türkçeye geç");
    });
}

document.addEventListener("DOMContentLoaded", () => {
    const savedLang = localStorage.getItem("language") || (navigator.language || "tr").slice(0, 2);
    setLanguage(savedLang === "en" ? "en" : "tr");

    document.querySelectorAll("[data-lang-switch]").forEach((button) => {
        button.addEventListener("click", () => {
            const current = document.documentElement.lang === "en" ? "en" : "tr";
            setLanguage(current === "tr" ? "en" : "tr");
        });
    });
});
